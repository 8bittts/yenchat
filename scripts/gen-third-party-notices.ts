#!/usr/bin/env bun
/**
 * Write yen-terminal/customizations/notices/ThirdPartyComponents.txt: the license text of
 * every library and font the terminal engine compiles into YEN.app, and of Sparkle.
 *
 * The list is yen-terminal/customizations/third-party-components.json. Each license text
 * comes from the archive the engine build pins in its build.zig.zon files, so the notice
 * matches what ships. tests/171-third-party-notices.test.ts fails when a vendor update
 * changes a pin or adds a dependency the list does not name; run this script then.
 *
 *   bun scripts/gen-third-party-notices.ts
 */
import { spawnSync } from "node:child_process";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { basename, join } from "node:path";
import {
	type BundledComponent,
	ENGINE_DIR,
	NOTICE_PATH,
	provenanceLines,
	readManifest,
	spmPin,
	zonArchiveUrl,
} from "./lib/third-party-components";

const repoRoot = process.cwd();
const archiveCache = join(tmpdir(), "yen-third-party-archives");
const RULE = "-".repeat(80);

const HEADER = `Third-party components in YEN

YEN's terminal engine (its own notice is TerminalEngine.txt) compiles the
libraries and fonts below into YEN.app, and YEN ships the Sparkle update
framework. Each section names the component, its license, where its source
is, and the license text that came with it.

This file is generated by scripts/gen-third-party-notices.ts from
yen-terminal/customizations/third-party-components.json.
`;

function clean(text: string): string {
	return text
		.replace(/\r\n?/g, "\n")
		.replace(/[ \t]+$/gm, "")
		.trim();
}

async function download(url: string, target: string): Promise<void> {
	const response = await fetch(url);
	if (!response.ok) throw new Error(`${url} answered ${response.status}`);
	writeFileSync(target, Buffer.from(await response.arrayBuffer()));
}

async function fetchText(url: string): Promise<string> {
	const response = await fetch(url);
	if (!response.ok) throw new Error(`${url} answered ${response.status}`);
	return response.text();
}

async function cachedArchive(url: string): Promise<string> {
	mkdirSync(archiveCache, { recursive: true });
	const target = join(archiveCache, basename(new URL(url).pathname));
	if (!existsSync(target)) await download(url, target);
	return target;
}

function tar(args: string[]): string {
	const result = spawnSync("tar", args, {
		encoding: "utf8",
		maxBuffer: 64 * 1024 * 1024,
	});
	if (result.status !== 0) {
		throw new Error(`tar ${args.join(" ")} failed: ${result.stderr}`);
	}
	return result.stdout;
}

/** A file at the archive root, or one level below it, by its path from there. */
function archiveMember(archive: string, file: string): string {
	const pattern = new RegExp(
		`^(\\./)?([^/]+/)?${file.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")}$`,
	);
	const member = tar(["-tf", archive])
		.split("\n")
		.find((entry) => pattern.test(entry) && !/(^|\/)\._/.test(entry));
	if (!member) throw new Error(`${basename(archive)} has no ${file}`);
	return tar(["-xOf", archive, member]);
}

async function licenseTexts(component: BundledComponent): Promise<string[]> {
	const { source } = component;
	if (source.licenseUrl) {
		const url = source.spm
			? source.licenseUrl.replace(
					"{revision}",
					spmPin(repoRoot, source.spm, component.key).revision,
				)
			: source.licenseUrl;
		return [await fetchText(url)];
	}
	if (source.local) {
		const dir = join(repoRoot, ENGINE_DIR, source.local);
		return component.files.map((file) => readFileSync(join(dir, file), "utf8"));
	}
	if (!source.zon) throw new Error(`${component.key} names no source`);
	const archive = await cachedArchive(
		zonArchiveUrl(repoRoot, source.zon, component.key),
	);
	return component.files.map((file) => archiveMember(archive, file));
}

async function section(component: BundledComponent): Promise<string> {
	const parts = [provenanceLines(repoRoot, component).join("\n")];
	if (component.note) parts.push(component.note);
	for (const text of await licenseTexts(component)) parts.push(clean(text));
	return `${RULE}\n\n${parts.join("\n\n")}\n`;
}

async function main(): Promise<void> {
	const manifest = readManifest(repoRoot);
	const sections: string[] = [];
	for (const component of manifest.bundled) {
		sections.push(await section(component));
		console.log(`[notices] ${component.key}: ${component.license}`);
	}
	writeFileSync(
		join(repoRoot, NOTICE_PATH),
		`${HEADER}\n${sections.join("\n")}`,
	);
	console.log(
		`[notices] wrote ${NOTICE_PATH} with ${sections.length} components`,
	);
}

await main();
