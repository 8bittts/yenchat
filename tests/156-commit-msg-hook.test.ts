import { afterAll, beforeAll, describe, expect, test } from "bun:test";
import { spawnSync } from "node:child_process";
import {
	mkdtempSync,
	readFileSync,
	rmSync,
	statSync,
	writeFileSync,
} from "node:fs";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";

const hook = resolve(import.meta.dir, "../.githooks/commit-msg");
const human = {
	GIT_AUTHOR_NAME: "8BIT",
	GIT_AUTHOR_EMAIL: "1309181+8bittts@users.noreply.github.com",
	GIT_COMMITTER_NAME: "8BIT",
	GIT_COMMITTER_EMAIL: "1309181+8bittts@users.noreply.github.com",
};

const baseEnv = () => ({
	NODE_ENV: "test" as const,
	PATH: process.env.PATH ?? "",
});
let dir = "";
beforeAll(() => {
	dir = mkdtempSync(join(tmpdir(), "commit-msg-"));
});
afterAll(() => {
	rmSync(dir, { recursive: true, force: true });
});

function run(message: string, env: Record<string, string> = human) {
	const file = join(dir, "COMMIT_EDITMSG");
	writeFileSync(file, message);
	return spawnSync("sh", [hook, file], {
		encoding: "utf8",
		env: {
			NODE_ENV: "test" as const,
			PATH: process.env.PATH ?? "",
			HOME: dir,
			GIT_CONFIG_NOSYSTEM: "1",
			GIT_CONFIG_GLOBAL: "/dev/null",
			...env,
		},
	});
}

describe("commit-msg hook", () => {
	test("is executable and wired through the prepare script", () => {
		expect(statSync(hook).mode & 0o111).not.toBe(0);
		const pkg = JSON.parse(
			readFileSync(resolve(import.meta.dir, "../package.json"), "utf8"),
		);
		expect(pkg.scripts.prepare).toBe("bun scripts/setup-hooks.ts");
		expect(
			readFileSync(
				resolve(import.meta.dir, "../scripts/setup-hooks.ts"),
				"utf8",
			),
		).toContain(".githooks");
	});

	test("accepts a plain human commit and a human co-author", () => {
		expect(run("docs: tidy the wallet notes\n").status).toBe(0);
		expect(
			run(
				"feat: add thing\n\nCo-authored-by: Bert Smith <bert@example.com>\nSigned-off-by: 8BIT <1309181+8bittts@users.noreply.github.com>\n",
			).status,
		).toBe(0);
	});

	test("accepts human co-authors whose names contain an agent word", () => {
		const trailers = [
			"Co-authored-by: Haider Ali <haider@example.com>",
			"Co-authored-by: Devin Smith <devin@example.com>",
			"Signed-off-by: Raider Jones <raider@example.com>",
		];
		for (const trailer of trailers) {
			expect(run(`feat: thing\n\n${trailer}\n`).status).toBe(0);
		}
	});

	test("accepts a human author whose name contains an agent word", () => {
		const result = run("feat: thing\n", {
			...human,
			GIT_AUTHOR_NAME: "Haider Ali",
			GIT_AUTHOR_EMAIL: "haider@example.com",
		});
		expect(result.status).toBe(0);
	});

	test("rejects the whole-name agents", () => {
		for (const trailer of [
			"Co-authored-by: Aider <aider@example.com>",
			"Co-authored-by: Devin-AI <devin-ai-integration[bot]@users.noreply.github.com>",
			"Co-authored-by: xAI <noreply@x.ai>",
		]) {
			expect(run(`feat: thing\n\n${trailer}\n`).status).toBe(1);
		}
	});

	test("accepts prose that only discusses agent names", () => {
		const message =
			"docs: forbid AI authors\n\nExisting commits by Cursor Agent stay. Claude and Codex trailers are refused.\n";
		expect(run(message).status).toBe(0);
	});

	test("ignores comment lines and the scissors section", () => {
		const message =
			"fix: thing\n# Co-authored-by: Claude <noreply@anthropic.com>\n# ------------------------ >8 ------------------------\nCo-authored-by: Codex <x@y.z>\n";
		expect(run(message).status).toBe(0);
	});

	test.each([
		"Co-authored-by: Cursor Agent <cursoragent@cursor.com>",
		"co-authored-by: Claude <noreply@anthropic.com>",
		"Co-authored-by: Codex <codex@openai.com>",
		"Co-authored-by: Grok <grok@x.ai>",
		"Co-authored-by: GitHub Copilot <copilot@github.com>",
		"Co-authored-by: ChatGPT <chatgpt@openai.com>",
		"Signed-off-by: Cursor Agent <cursoragent@cursor.com>",
		"  Signed-off-by: Claude <noreply@anthropic.com>",
	])("rejects trailer: %s", (trailer) => {
		const result = run(`feat: thing\n\nbody\n\n${trailer}\n`);
		expect(result.status).toBe(1);
		expect(result.stderr).toContain("[FAIL] commit-msg");
	});

	test.each([
		"Generated with Claude Code",
		"🤖 Generated with [Claude Code](https://claude.com/claude-code)",
		"Generated by Codex",
		"Co-authored with Cursor",
		"AI-assisted change",
	])("rejects phrase: %s", (phrase) => {
		expect(run(`feat: thing\n\n${phrase}\n`).status).toBe(1);
	});

	test.each([
		{
			GIT_AUTHOR_NAME: "Cursor Agent",
			GIT_AUTHOR_EMAIL: "cursoragent@cursor.com",
		},
		{ GIT_AUTHOR_NAME: "Claude", GIT_AUTHOR_EMAIL: "noreply@anthropic.com" },
		{ GIT_AUTHOR_NAME: "8BIT", GIT_AUTHOR_EMAIL: "cursoragent@cursor.com" },
		{ GIT_COMMITTER_NAME: "Codex", GIT_COMMITTER_EMAIL: "codex@example.com" },
		{
			GIT_COMMITTER_NAME: "8BIT",
			GIT_COMMITTER_EMAIL: "noreply@anthropic.com",
		},
	])("rejects an AI author or committer: %j", (override) => {
		const result = run("feat: thing\n", { ...human, ...override });
		expect(result.status).toBe(1);
		expect(result.stderr).toContain("an AI agent");
	});

	test("fails closed on an unreadable message and on an unreadable identity", () => {
		const missing = spawnSync("sh", [hook, join(dir, "does-not-exist")], {
			encoding: "utf8",
			env: baseEnv(),
		});
		expect(missing.status).toBe(1);
		const noArg = spawnSync("sh", [hook], { encoding: "utf8", env: baseEnv() });
		expect(noArg.status).toBe(1);
		const noIdentity = run("feat: thing\n", { ...human, GIT_AUTHOR_NAME: "" });
		expect(noIdentity.status).toBe(1);
	});

	test("blocks a real commit in a scratch repository, without --no-verify", () => {
		const repo = join(dir, "repo");
		const env = {
			NODE_ENV: "test" as const,
			PATH: process.env.PATH ?? "",
			HOME: dir,
			GIT_CONFIG_NOSYSTEM: "1",
			GIT_CONFIG_GLOBAL: "/dev/null",
		};
		const git = (args: string[], extra: Record<string, string> = {}) =>
			spawnSync(
				"git",
				[
					"-c",
					`core.hooksPath=${resolve(import.meta.dir, "../.githooks")}`,
					...args,
				],
				{
					cwd: repo,
					encoding: "utf8",
					env: { ...env, ...extra },
				},
			);
		expect(
			spawnSync("git", ["init", "-q", repo], { encoding: "utf8", env }).status,
		).toBe(0);
		const blocked = git(["commit", "--allow-empty", "-q", "-m", "chore: one"], {
			GIT_AUTHOR_NAME: "Cursor Agent",
			GIT_AUTHOR_EMAIL: "cursoragent@cursor.com",
			GIT_COMMITTER_NAME: "8BIT",
			GIT_COMMITTER_EMAIL: "1309181+8bittts@users.noreply.github.com",
		});
		expect(blocked.status).not.toBe(0);
		expect(blocked.stderr).toContain("[FAIL] commit-msg");
		const allowed = git(
			["commit", "--allow-empty", "-q", "-m", "chore: two"],
			human,
		);
		expect(allowed.status).toBe(0);
	});
});
